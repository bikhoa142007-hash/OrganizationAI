import { test, expect, type Page } from '@playwright/test'
import { resolve } from 'node:path'

const image = resolve(import.meta.dirname, '../../tests/fixtures/ba/v2.1/images/creative-pass.png')
async function fillPlan(page: Page, title: string, budget: string) {
  await page.goto('/demo/plans/new')
  await page.getByLabel('Tên chiến dịch').fill(title)
  await page.getByRole('textbox', { name: /^Mục tiêu \*/ }).fill('Synthetic browser campaign')
  await page.getByLabel('Ngày bắt đầu').fill('2026-10-01')
  await page.getByLabel('Ngày kết thúc').fill('2026-10-31')
  await page.getByLabel('Ngân sách').fill(budget)
  await page.getByLabel('Tóm tắt').fill('Browser smoke strategy')
  await page.getByLabel('Ảnh đính kèm', { exact: true }).setInputFiles(image)
}

test('Maker submits mock pass, then assigned Checker approves with persisted evidence', async ({ page, request }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await fillPlan(page, 'E2E auto campaign', '50000000')
  await page.getByRole('button', { name: 'Lưu draft' }).click()
  await expect(page).toHaveURL(/\/edit$/)
  await expect(page.getByText('1 ảnh đã lưu trên backend')).toBeVisible()
  await page.getByRole('button', { name: 'Gửi duyệt', exact: true }).click()
  await expect(page).toHaveURL(/\/result$/)
  await expect(page.getByText('PENDING_APPROVAL · POLICY_OUT_OF_SCOPE')).toBeVisible()
  const id = page.url().split('/').at(-2)!
  const response = await request.get(`http://127.0.0.1:8008/api/plans/${id}`, { headers: { 'X-Demo-Actor': 'DEMO-MAKER-01' } })
  const history = await response.json()
  expect(history.plan.state.plan_status).toBe('PENDING_APPROVAL')
  expect(history.versions).toHaveLength(1)
  expect(history.audit.some((e: { action: string }) => e.action === 'AUTO_APPROVED')).toBeFalsy()
  expect(history.rounds[0].final_id).toBeNull()
  await page.getByRole('link', { name: 'Version / round / history' }).click()
  await expect(page.getByText('Version 1 / Round 1', { exact: true })).toBeVisible()
  await expect(page.getByRole('img')).toBeVisible()
  await page.screenshot({ path: 'test-results/auto-history.png', fullPage: true })
  await expect(page.getByRole('link', { name: 'Chờ tôi duyệt', exact: true })).toHaveCount(0)
  await page.getByLabel('Demo actor').selectOption('DEMO-CHECKER-01')
  await expect(page.getByRole('link', { name: 'Hồ sơ mới' })).toHaveCount(0)
  await page.getByRole('link', { name: 'Chờ tôi duyệt', exact: true }).click()
  await page.getByText('E2E auto campaign', { exact: true }).click()
  await expect(page.getByText('Khuyến nghị AI (không phải quyết định cuối)')).toBeVisible()
  await page.locator('#review-reason').fill('Campaign evidence reviewed by the assigned Checker')
  await page.getByRole('button', { name: 'Approve', exact: true }).click()
  await page.getByRole('button', { name: 'Xác nhận', exact: true }).click()
  await expect(page.getByText('Quyết định đã được lưu cùng audit.')).toBeVisible()
  await page.goto(`/demo/plans/${id}/result`)
  await expect(page.getByRole('heading', { name: 'E2E auto campaign', exact: true })).toBeVisible()
  const finalResponse = await request.get(`http://127.0.0.1:8008/api/plans/${id}`, { headers: { 'X-Demo-Actor': 'DEMO-CHECKER-01' } })
  const finalHistory = await finalResponse.json()
  expect(finalHistory.plan.state.plan_status).toBe('APPROVED')
  expect(finalHistory.audit.some((e: { action: string }) => e.action === 'HUMAN_APPROVED')).toBeTruthy()
  expect(errors).toEqual([])
})

test('Human Review: Checker rejects, Maker resubmits and history preserves both rounds', async ({ page, request }) => {
  await fillPlan(page, 'E2E budget review', '100000001')
  await page.getByRole('button', { name: 'Gửi duyệt', exact: true }).click()
  await expect(page).toHaveURL(/\/result$/)
  await expect(page.getByText('PENDING_APPROVAL · AUTHORITY_EXCEEDED')).toBeVisible()
  const id = page.url().split('/').at(-2)!
  await page.getByLabel('Demo actor').selectOption('DEMO-CHECKER-01')
  await page.getByRole('link', { name: 'Chờ tôi duyệt', exact: true }).click()
  await page.getByText('E2E budget review', { exact: true }).click()
  await page.locator('#review-reason').fill('Reduce budget and resubmit')
  await page.getByLabel('Lý do override').fill('Budget exceeds approved mandate despite model recommendation')
  await page.getByRole('button', { name: 'Reject', exact: true }).click()
  await page.getByRole('button', { name: 'Xác nhận', exact: true }).click()
  await expect(page.getByText('Quyết định đã được lưu cùng audit.')).toBeVisible()
  await page.getByLabel('Demo actor').selectOption('DEMO-MAKER-01')
  await page.getByRole('link', { name: /^E2E budget review DEMO-/ }).click()
  await page.getByRole('link', { name: 'Sửa và gửi lại' }).click()
  await page.getByLabel('Ngân sách').fill('50000000')
  await page.getByRole('button', { name: 'Gửi duyệt', exact: true }).click()
  await expect(page).toHaveURL(/\/result$/)
  await expect(page.getByText('PENDING_APPROVAL · POLICY_OUT_OF_SCOPE')).toBeVisible()
  const response = await request.get(`http://127.0.0.1:8008/api/plans/${id}`, { headers: { 'X-Demo-Actor': 'DEMO-MAKER-01' } })
  const history = await response.json()
  expect(history.versions).toHaveLength(2)
  expect(history.versions[0].payload.budget_minor_units).toBe('100000001')
  expect(history.versions[1].payload.budget_minor_units).toBe('50000000')
  expect(history.records.filter((r: { kind: string }) => r.kind === 'human_decision')).toHaveLength(1)
})

